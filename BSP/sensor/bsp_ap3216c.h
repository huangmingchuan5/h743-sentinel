/**
  ******************************************************************************
  * @file    bsp_ap3216c.h
  * @brief   AP3216C 光/接近传感器驱动（I2C4，7 位地址 0x1E）。
  *
  *          只做本项目要用的部分：软复位、ALS+PS 模式、读 ALS/PS 原始值。
  *          每次操作自带 I2C 总线加锁（与 EEPROM / MPU6050 共享 I2C4）。
  *
  *          说明：移植自野火《AP3216C 全功能例程》的寄存器操作，
  *          去掉了中断引脚配置和阈值设置（本项目轮询读取，不用 INT）。
  ******************************************************************************
  */

#ifndef __BSP_AP3216C_H
#define __BSP_AP3216C_H

#include "main.h"

#define AP3216C_ADDR7   0x1Eu

/** 初始化：软复位 → ALS+PS 模式（内部有 2 × 100 ms 等待，开机阶段调用一次）。
  * @retval 0 = 成功；0x21 = 抢总线超时；其它 = I2C 错误码 */
uint8_t Ap3216c_Init(void);

/** 读环境光原始值（16 bit counts）。
  * @retval 0 = 成功；非 0 = 错误码 */
uint8_t Ap3216c_ReadAls(uint16_t *raw);

/** 读接近数据：*ps = 低 10 位数据 | bit15 "接近"标志。
  * @retval 0 = 有效；1 = PS/IR 溢出（物体很近/强红外，数据仅供参考）；其它 = I2C 错误码 */
uint8_t Ap3216c_ReadPs(uint16_t *ps);

#endif /* __BSP_AP3216C_H */
