/**
  ******************************************************************************
  * @file    bsp_mpu6050.h
  * @brief   MPU6050 六轴传感器驱动（I2C4，7 位地址 0x68）。
  *
  *          本项目只用加速度：初始化 + 读三轴加速度原始值。
  *          每次操作自带 I2C 总线加锁（与 EEPROM / AP3216C 共享 I2C4）。
  *
  *          配置：采样率 125 Hz、DLPF 44 Hz、加速度 ±4g（8192 LSB/g）、陀螺 ±2000dps。
  ******************************************************************************
  */

#ifndef __BSP_MPU6050_H
#define __BSP_MPU6050_H

#include "main.h"

#define MPU6050_ADDR7   0x68u		//MPU6050 作为 I2C 从设备的 7 位地址

/** 初始化：上电等待 → 唤醒 → 采样率/滤波/量程配置（开机阶段调用一次）。
  * @retval 0 = 成功；0x21 = 抢总线超时；0x30 = WHO_AM_I 不是 0x68；其它 = I2C 错误码 */
uint8_t Mpu6050_Init(void);

/** WHO_AM_I 的值（诊断用；初始化失败时为 0）。 */
uint8_t Mpu6050_WhoAmI(void);

/** 读三轴加速度原始值（±4g 量程下 8192 LSB = 1g）。
  * @retval 0 = 成功；非 0 = 错误码 */
uint8_t Mpu6050_ReadAccel(int16_t *ax, int16_t *ay, int16_t *az);

#endif /* __BSP_MPU6050_H */
